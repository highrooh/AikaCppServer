CryptoResult encrypt_frame(
    const std::span<std::byte> frame,
    const std::uint8_t random_key,
    const std::uint32_t timestamp_ms) noexcept {
    if (frame.size() < 12U) {
        return {CryptoError::insufficient_bytes};
    }
    if (frame.size() > std::numeric_limits<std::uint16_t>::max()) {
        return {CryptoError::invalid_packet_size};
    }

    write_u16_le(static_cast<std::uint16_t>(frame.size()), frame, 0U);
    frame[2] = std::byte{0};
    frame[3] = static_cast<std::byte>(random_key);
    write_u32_le(timestamp_ms, frame, 8U);

    std::uint32_t sum_plain = 0U;
    std::uint32_t sum_cipher = 0U;
    auto position = key_position(random_key);
    std::uint32_t iteration = 1U;

    for (std::size_t offset = 4U;
         iteration < (frame.size() >> 2U);
         offset += 4U, ++iteration, ++position) {
        const auto original = read_u32_le(frame, offset);
        sum_plain += original;
        const auto key = transform_key(key_for(position), iteration);
        std::uint32_t encrypted = original;
        if ((iteration & 1U) == 0U) {
            encrypted += key;
        } else {
            encrypted -= key;
        }
        write_u32_le(encrypted, frame, offset);
        sum_cipher += encrypted;
    }

    frame[2] = static_cast<std::byte>((sum_cipher - sum_plain) & 0xFFU);
    return {CryptoError::none};
}

CryptoResult decrypt_frame(const std::span<std::byte> frame) noexcept {
    if (frame.size() < 2U) {
        return {CryptoError::insufficient_bytes};
    }

    const auto packet_size = read_u16_le(frame, 0U);
    if (packet_size < 12U) {
        return {CryptoError::invalid_packet_size};
    }
    if (packet_size > frame.size()) {
        return {CryptoError::insufficient_bytes};
    }

    const auto packet = frame.first(packet_size);
    const auto random_key = std::to_integer<std::uint8_t>(packet[3]);
    auto position = key_position(random_key);
    std::uint32_t sum_cipher = 0U;
    std::uint32_t sum_plain = 0U;
    std::uint32_t iteration = 1U;

    for (std::size_t offset = 4U;
         iteration < (packet.size() >> 2U);
         offset += 4U, ++iteration, ++position) {
        const auto encrypted = read_u32_le(packet, offset);
        sum_cipher += encrypted;
        const auto key = transform_key(key_for(position), iteration);
        std::uint32_t plain = encrypted;
        if ((iteration & 1U) == 0U) {
            plain -= key;
        } else {
            plain += key;
        }
        write_u32_le(plain, packet, offset);
        sum_plain += plain;
    }

    const auto expected = static_cast<std::uint8_t>((sum_cipher - sum_plain) & 0xFFU);
    const auto received = std::to_integer<std::uint8_t>(packet[2]);
    return {received == expected ? CryptoError::none : CryptoError::checksum_mismatch};
}

